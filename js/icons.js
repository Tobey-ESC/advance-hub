AH.icon = function (name, extraClass) {
  var body = AH.ICONS[name] || "";
  return '<svg class="icon' + (extraClass ? " " + extraClass : "") + '" viewBox="0 0 24 24" aria-hidden="true" focusable="false">' + body + "</svg>";
};

/** Replace <span data-icon="name"></span> placeholders found in static HTML. */
AH.hydrateIcons = function (root) {
  (root || document).querySelectorAll("[data-icon]").forEach(function (el) {
    el.outerHTML = AH.icon(el.getAttribute("data-icon"), el.getAttribute("data-icon-class") || "");
  });
};

